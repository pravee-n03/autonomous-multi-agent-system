"""
Agent State Definition
=======================
Shared state schema used by all agents in the LangGraph workflow.

This includes agentic fields that enable:
- Quality-based routing (quality_score, pass_decision)
- Human-in-the-loop (plan_approved)
- Visible tool usage (tool_calls_log)
- Reasoning transparency (agent_reasoning)
"""

from typing import TypedDict, List


class AgentState(TypedDict):
    """The shared state passed between all agents in the graph.

    Core fields:
        task: The user-provided topic or task description.
        plan: The outline/plan generated by the planning agent.
        draft: The current draft of the report.
        critique: Feedback from the reflection agent.
        content: Accumulated research content from searches.
        revision_number: Current revision iteration count.
        max_revisions: Maximum number of revision loops allowed.

    Agentic fields:
        quality_score: 1-10 score assigned by the reflection agent.
        pass_decision: Whether the reflection agent approved the draft.
        plan_approved: Whether the human approved the plan (human-in-the-loop).
        tool_calls_log: Record of every tool call made by every agent.
        agent_reasoning: Current agent's reasoning trace (overwritten each step).
    """
    task: str
    plan: str
    draft: str
    critique: str
    content: List[str]
    revision_number: int
    max_revisions: int

    # ── Agentic fields ──
    quality_score: int
    pass_decision: bool
    plan_approved: bool
    tool_calls_log: List[dict]
    agent_reasoning: dict
